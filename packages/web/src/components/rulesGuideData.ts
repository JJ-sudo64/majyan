export interface YakuEntry {
  name: string;
  /** 門前の翻数。役満は「役満」「ダブル役満」。 */
  han: string;
  /** 鳴いた時の翻数。鳴けない役は"-"、変わらない役はhanと同じ。 */
  openHan: string;
  description: string;
}

export interface YakuGroup {
  id: string;
  label: string;
  yaku: YakuEntry[];
}

